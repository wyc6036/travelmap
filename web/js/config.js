/**
 * 一组地点属于哪个"区域"，用于足迹时间线上的一次行程。
 *   · 同一国家      → 国家名（「京都赏樱」写「日本」，比写「亚洲」有意义）
 *   · 跨国家但同洲  → 大洲名（「西欧初见」= 巴黎 + 巴塞罗那 → 欧洲）
 *   · 跨洲          → 把各国名并列出来（宁可啰嗦，也不要谎报成一个洲）
 *
 * 放在 config.js 而不是 utils.js：utils.js 的约定是"零依赖纯函数"，
 * 而这里要用到上面的 CONTINENT_BY_COUNTRY；config.js 无依赖、且两个 UI 模块都已引入它。
 */
export function regionLabel(places) {
  const countries = [...new Set((places || [])
    .map((p) => p && (p.countryZh || p.country))
    .filter(Boolean))];
  if (countries.length <= 1) return countries[0] || '';
  const conts = [...new Set(countries.map((c) => CONTINENT_BY_COUNTRY[c]).filter(Boolean))];
  if (conts.length === 1) return conts[0];
  return countries.join(' · ');
}

